import PDFDocument from 'pdfkit';
import { formatIndiaDateTime } from '../common/instant.js';
import type { BillDto, PaymentDto } from './billing.mapper.js';

export type InvoicePdfSociety = {
  name: string;
  addressLine1: string | null;
  addressLine2: string | null;
  city: string | null;
  state: string | null;
  postalCode: string | null;
};

function formatInr(value: string): string {
  const amount = Number(value);
  if (Number.isNaN(amount)) return `INR ${value}`;
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: 2,
  }).format(amount);
}

function paymentStatusLabel(status: BillDto['status']): string {
  switch (status) {
    case 'PAID':
      return 'PAID';
    case 'PARTIALLY_PAID':
      return 'PARTIALLY PAID';
    case 'OVERDUE':
      return 'UNPAID (OVERDUE)';
    case 'CANCELLED':
      return 'CANCELLED';
    case 'DRAFT':
      return 'DRAFT';
    default:
      return 'UNPAID';
  }
}

function addressLines(society: InvoicePdfSociety): string[] {
  return [
    society.addressLine1,
    society.addressLine2,
    [society.city, society.state, society.postalCode].filter(Boolean).join(', '),
  ].filter((line): line is string => Boolean(line && line.trim()));
}

export async function buildInvoicePdf(input: {
  society: InvoicePdfSociety;
  bill: BillDto;
  payments: PaymentDto[];
}): Promise<Buffer> {
  const { society, bill, payments } = input;
  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  const chunks: Buffer[] = [];

  return new Promise((resolve, reject) => {
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(18).text(society.name, { continued: false });
    doc.fontSize(10).fillColor('#334155');
    for (const line of addressLines(society)) {
      doc.text(line);
    }
    doc.moveDown();
    doc.fillColor('#0f172a').fontSize(14).text('Maintenance Invoice');
    doc.moveDown(0.5);

    doc.fontSize(10);
    doc.text(`Invoice number: ${bill.invoiceNumber}`);
    doc.text(
      `Unit: ${bill.buildingCode ?? '—'}-${bill.unitNumber ?? '—'}`,
    );
    doc.text(
      `Billing period: ${bill.periodYear}-${String(bill.periodMonth).padStart(2, '0')} (${bill.periodStart} to ${bill.periodEnd})`,
    );
    doc.text(`Invoice date: ${bill.invoiceDate}`);
    doc.text(`Due date: ${bill.dueDate}`);
    doc.text(`Status: ${paymentStatusLabel(bill.status)}`);
    doc.moveDown();

    doc.fontSize(12).text('Charges');
    doc.moveDown(0.3);
    doc.fontSize(10);
    const lines =
      bill.lineItems && bill.lineItems.length > 0
        ? bill.lineItems
        : [
            {
              id: 'base',
              description: 'Base maintenance',
              amount: bill.baseAmount,
              lineType: 'BASE' as const,
            },
            ...(Number(bill.additionalAmount) > 0
              ? [
                  {
                    id: 'addl',
                    description: 'Additional charges',
                    amount: bill.additionalAmount,
                    lineType: 'ADDITIONAL' as const,
                  },
                ]
              : []),
            ...(Number(bill.discountAmount) > 0
              ? [
                  {
                    id: 'disc',
                    description: 'Discount',
                    amount: bill.discountAmount,
                    lineType: 'DISCOUNT' as const,
                  },
                ]
              : []),
          ];

    for (const item of lines) {
      const prefix = item.lineType === 'DISCOUNT' ? '-' : '';
      doc.text(
        `${item.description}: ${prefix}${formatInr(item.amount)}`,
      );
    }
    doc.moveDown(0.5);
    doc.fontSize(11).text(`Total: ${formatInr(bill.totalAmount)}`);
    doc.text(`Paid: ${formatInr(bill.paidAmount)}`);
    doc.text(`Outstanding: ${formatInr(bill.outstandingAmount)}`);
    doc.moveDown();

    doc.fontSize(12).text('Payments');
    doc.moveDown(0.3);
    doc.fontSize(10);
    const recorded = payments.filter((payment) => payment.status === 'RECORDED');
    if (recorded.length === 0) {
      doc.text('No payments recorded.');
    } else {
      for (const payment of recorded) {
        doc.text(
          `${formatInr(payment.amount)} · ${payment.method} · ${formatIndiaDateTime(payment.paidAt)}${
            payment.referenceNumber ? ` · Ref ${payment.referenceNumber}` : ''
          }`,
        );
      }
    }

    doc.moveDown(2);
    doc.fontSize(8).fillColor('#64748b').text(
      'Generated by HomelyBlock from server-side invoice records. Totals are not client-supplied.',
    );

    doc.end();
  });
}
