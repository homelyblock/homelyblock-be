import { ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsEnum, IsInt, IsOptional, Max, Min } from 'class-validator';
import { NoticeStatus } from '../../generated/prisma/client.js';

export class ListNoticesQueryDto {
  @ApiPropertyOptional({ default: 1 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  page?: number = 1;

  @ApiPropertyOptional({ default: 20 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(50)
  limit?: number = 20;

  @ApiPropertyOptional({
    enum: NoticeStatus,
    description: 'Admins may filter by status; residents always see PUBLISHED',
  })
  @IsOptional()
  @IsEnum(NoticeStatus)
  status?: NoticeStatus;
}
